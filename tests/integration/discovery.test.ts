import { afterAll, beforeAll, expect, inject, test } from "vitest";

import {
  clearResetCache,
  DISCOVERY_QUERY,
  prepareReset,
  type DiscoveredRelation,
} from "../../src/reset.js";
import { db } from "../db/client.js";

// The discovery query and the Reset against shapes the fixture schema does not carry:
// a second schema whose name needs quoting, a reserved-word table, a name holding a space
// and both kinds of quote, an identity column, a partitioned table, a standalone
// sequence, and a table an extension owns. Built with raw SQL and dropped afterwards,
// so the Prisma migrations stay the smallest shape that exercises the harness.
//
// This file never calls `setupDatabase(db)`: it drives `prepareReset` itself, after the
// fixture exists, so discovery sees it. Files sharing this Worker Database run one at a
// time and each opens with a Reset, so the fixture is invisible to them as long as it is
// dropped here.
//
// The fixture is DDL run mid-run, which the Reset's discovery cache does not expect: it
// keeps one discovery per Worker Database for as long as `src/reset.ts` lives — every
// file a worker runs, under `isolate: false`. So the cache is cleared once the fixture
// exists, or this file's Reset would come from an earlier file's discovery and miss it,
// and again once it is dropped, or later files on this worker would get a Reset naming
// tables that no longer exist. A consumer has no such hook: under `isolate: false`
// schema changes belong in the migrations.

const SCHEMA = '"Reset Fixture"';
const ODD = `${SCHEMA}."it's ""odd"""`;

const FIXTURE = [
  `CREATE SCHEMA ${SCHEMA}`,
  `CREATE TABLE ${SCHEMA}."order" (id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)`,
  `CREATE TABLE ${ODD} (id serial PRIMARY KEY, order_id int REFERENCES ${SCHEMA}."order")`,
  `CREATE TABLE ${SCHEMA}.measurement (id bigserial, at date NOT NULL) PARTITION BY RANGE (at)`,
  `CREATE TABLE ${SCHEMA}.measurement_2026 PARTITION OF ${SCHEMA}.measurement
     FOR VALUES FROM ('2026-01-01') TO ('2027-01-01')`,
  `CREATE SEQUENCE ${SCHEMA}.standalone`,
  `CREATE TABLE ${SCHEMA}.extension_owned (id int)`,
  // Any extension will do: membership is what the discovery query reads.
  `CREATE EXTENSION hstore`,
  `ALTER EXTENSION hstore ADD TABLE ${SCHEMA}.extension_owned`,
];

const TEARDOWN = [
  `ALTER EXTENSION hstore DROP TABLE ${SCHEMA}.extension_owned`,
  `DROP EXTENSION hstore`,
  `DROP SCHEMA ${SCHEMA} CASCADE`,
];

beforeAll(async () => {
  for (const statement of FIXTURE) await db.$executeRawUnsafe(statement);
  clearResetCache();
});

afterAll(async () => {
  // Every step runs even if an earlier one fails, so a half-built fixture still goes.
  for (const statement of TEARDOWN) await db.$executeRawUnsafe(statement).catch(() => {});
  clearResetCache();
});

const query = <T>(sql: string) => db.$queryRawUnsafe<T[]>(sql);

test("discovers parents, not partitions, and skips migrations and extension tables", async () => {
  const relations = await query<DiscoveredRelation>(DISCOVERY_QUERY);
  const fixture = relations
    .filter((relation) => relation.schema === "Reset Fixture")
    .map((relation) => `${relation.kind} ${relation.relkind} ${relation.name}`);

  // The relkind tells the Reset which tables it cannot probe: a partitioned parent (`p`)
  // has no file of its own.
  expect(fixture).toEqual([
    'sequence S it\'s "odd"_id_seq',
    "sequence S measurement_id_seq",
    "sequence S order_id_seq",
    'table r it\'s "odd"',
    "table p measurement",
    "table r order",
  ]);
  expect(relations.map((relation) => relation.name)).not.toContain("_prisma_migrations");
});

test("the Reset empties every discovered table and rewinds every owned sequence", async () => {
  // Arrange: rows everywhere, the standalone sequence advanced too.
  await db.$executeRawUnsafe(`INSERT INTO ${SCHEMA}."order" DEFAULT VALUES`);
  await db.$executeRawUnsafe(`INSERT INTO ${ODD} (order_id) VALUES (1)`);
  await db.$executeRawUnsafe(`INSERT INTO ${SCHEMA}.measurement (at) VALUES ('2026-06-01')`);
  await db.$executeRawUnsafe(`INSERT INTO ${SCHEMA}.extension_owned VALUES (7)`);
  await query(`SELECT nextval('${SCHEMA}.standalone')`);

  // Act
  const { reset } = await prepareReset(
    db,
    process.env.DATABASE_URL!,
    inject("templateDatabaseName"),
  );
  await reset();

  // Assert: empty, partitions included, and the next ids start over.
  const [counts] = await query<Record<string, number>>(
    `SELECT (SELECT count(*)::int FROM ${SCHEMA}."order") AS "order",
            (SELECT count(*)::int FROM ${ODD}) AS odd,
            (SELECT count(*)::int FROM ${SCHEMA}.measurement_2026) AS partition,
            (SELECT count(*)::int FROM ${SCHEMA}.extension_owned) AS extension_owned,
            (SELECT count(*)::int FROM _prisma_migrations) AS migrations`,
  );
  expect(counts).toMatchObject({ order: 0, odd: 0, partition: 0, extension_owned: 1 });
  expect(counts!.migrations).toBeGreaterThan(0);

  const [next] = await query<Record<string, number>>(
    `SELECT nextval(pg_get_serial_sequence('${SCHEMA}."order"', 'id'))::int AS "order",
            nextval(pg_get_serial_sequence('${ODD.replaceAll("'", "''")}', 'id'))::int AS odd,
            nextval(pg_get_serial_sequence('${SCHEMA}.measurement', 'id'))::int AS measurement,
            nextval('${SCHEMA}.standalone')::int AS standalone`,
  );
  expect(next).toEqual({ order: 1, odd: 1, measurement: 1, standalone: 2 });
});
